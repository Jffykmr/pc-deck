export const GLYPH_NAMES = Object.keys(ICONS);

export function Glyph({
  name,
  size = 24,
  weight = "regular",
  className,
}: {
  name?: string;
  size?: number;
  weight?: IconWeight;
  className?: string;
}) {
  const Cmp = (name && ICONS[name.toLowerCase()]) || AppWindowIcon;
  return <Cmp size={size} weight={weight} className={className} />;
}
